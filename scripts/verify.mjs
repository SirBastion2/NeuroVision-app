import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { checkStandalone } from "./check-standalone.mjs";

const root = fileURLToPath(new URL("..", import.meta.url));
const standaloneDir = join(root, "apps/web/dist/standalone");
const evidencePath = join(root, "docs/RELEASE_EVIDENCE.md");

function run(command, args) {
  const result = spawnSync(command, args, {
    cwd: root,
    encoding: "utf8",
    env: process.env,
  });
  if (result.stdout) process.stdout.write(result.stdout);
  if (result.stderr) process.stderr.write(result.stderr);
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }
  return `${result.stdout ?? ""}${result.stderr ?? ""}`;
}

function sumReporter(text) {
  let tests = 0;
  let pass = 0;
  let fail = 0;
  for (const line of text.split("\n")) {
    const testsMatch = line.match(/^# tests (\d+)/);
    const passMatch = line.match(/^# pass (\d+)/);
    const failMatch = line.match(/^# fail (\d+)/);
    if (testsMatch) tests += Number(testsMatch[1]);
    if (passMatch) pass += Number(passMatch[1]);
    if (failMatch) fail += Number(failMatch[1]);
  }
  return { tests, pass, fail };
}

function contractsVersion() {
  const source = readFileSync(join(root, "packages/domain/src/version.ts"), "utf8");
  const match = source.match(/export const CONTRACTS_VERSION = "([^"]+)"/);
  if (!match) {
    throw new Error("CONTRACTS_VERSION not found in packages/domain/src/version.ts");
  }
  return match[1];
}

function summarizeBuild(output) {
  const lines = output
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line.length > 0);
  const keep = lines.filter(
    (line) =>
      /built in|dist\/|standalone|✓|vite v|tsc|error|warning/i.test(line) && !line.startsWith("npm warn"),
  );
  return (keep.length > 0 ? keep : lines.slice(-20)).join("\n");
}

const generatedAt = new Date().toISOString();
const version = contractsVersion();

const buildOutput = run("npm", ["run", "build"]);
const testOutput = run("npm", ["test"]);
const e2eOutput = run("npm", ["run", "test:e2e"]);

if (!existsSync(standaloneDir)) {
  throw new Error(`Standalone output missing at ${standaloneDir}`);
}
const standalone = checkStandalone(standaloneDir);
const counts = {
  allPackages: sumReporter(testOutput),
  e2e: sumReporter(e2eOutput),
};
const uniqueTests = counts.allPackages.tests + counts.e2e.tests;
const uniquePass = counts.allPackages.pass + counts.e2e.pass;
const uniqueFail = counts.allPackages.fail + counts.e2e.fail;

const evidence = `# Release evidence

Generated by \`npm run verify\` on ${generatedAt}.

## Contracts

- \`CONTRACTS_VERSION\`: **${version}**

## Test counts

| Suite | Tests | Pass | Fail |
| --- | ---: | ---: | ---: |
| Package tests (\`npm test\`: domain, gaze, web integration + standalone check) | ${counts.allPackages.tests} | ${counts.allPackages.pass} | ${counts.allPackages.fail} |
| E2E through the service layer (\`npm run test:e2e\`) | ${counts.e2e.tests} | ${counts.e2e.pass} | ${counts.e2e.fail} |
| Unique tests in this verify run | ${uniqueTests} | ${uniquePass} | ${uniqueFail} |

\`npm test\` runs domain, gaze, and web integration/standalone checks (including the upload queue, mocked API polling, export, delete, and API-route sign-in). \`npm run test:e2e\` is the separate service-layer flow (live session start, score, save, reload, history comparison, practice + reflection, mocked API sign-in and upload queue, standalone offline).

## Build

Standalone file: \`${relative(root, standalone.file)}\` (${standalone.bytes} bytes)

\`\`\`
${summarizeBuild(buildOutput)}
\`\`\`

## Verify command

\`npm run verify\` runs \`npm run build\`, \`npm test\`, and \`npm run test:e2e\`, then checks that the standalone output is a single HTML file with no external script or stylesheet URLs.
`;

mkdirSync(dirname(evidencePath), { recursive: true });
writeFileSync(evidencePath, evidence);
console.log(`Wrote ${relative(root, evidencePath)}`);
console.log(`Standalone ${relative(root, standalone.file)} (${standalone.bytes} bytes)`);
